# Longest-first, single-pass replacement prevents a translated phrase being
# interpreted again as an English source message inside a joined note list.
_RECORD_SEPARATOR = re.compile(r"; (?=(?:" + "|".join(re.escape(key) for key in TR) + r"): )")
_CLINICAL_PHRASES = re.compile("|".join(
    re.escape(message) for message in sorted(TR_CLINICAL, key=len, reverse=True)
))


def translate_text(value: Any, locale: str = "en") -> str:
    text = "" if value is None else str(value)
    if normalize_locale(locale) != "tr" or not text:
        return text
    if text in TR_CLINICAL:
        return TR_CLINICAL[text]
    if text in TR:
        return TR[text]
    # Flattened renderer records retain explicit canonical key/value boundaries.
    # Translate exact keys/values, not substrings inside source IDs or version strings.
    if text.startswith("ML7 ") and text[4:] in TR:
        return "ML7 " + TR[text[4:]]
    parts = _RECORD_SEPARATOR.split(text)
    if len(parts) > 1:
        return "; ".join(translate_text(part, locale) for part in parts)
    key, separator, value = text.partition(": ")
    if separator and key in TR:
        return TR[key] + separator + translate_text(value, locale)
    # BAD classifications combine an existing category, status/range and information note.
    classification, separator, rest = text.partition(" / ")
    if separator and classification in {"NORMAL", "SUSPICIOUS", "ABNORMAL", "UNAVAILABLE"}:
        return TR[classification] + separator + translate_text(rest, locale)
    if text.endswith("; information only"):
        return translate_text(text.removesuffix("; information only"), locale) + "; yalnızca bilgilendirme"
    translated = _CLINICAL_PHRASES.sub(lambda match: TR_CLINICAL[match.group(0)], text)
    for pattern, replacement in REPLACEMENTS:
        translated = re.sub(pattern, replacement, translated, flags=re.IGNORECASE)
    return translated.replace(".; ", ". ")


